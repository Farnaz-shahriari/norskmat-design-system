/* ---------------------------------------------------------------------------
   Generates src/index.ts, the package's public surface.

   Generated rather than hand written so it can never fall behind the folder,
   which is the same failure mode this repo keeps finding everywhere else. Runs
   as part of npm run build.
   --------------------------------------------------------------------------- */
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const COMPONENTS = join(ROOT, "src", "components");

const files = readdirSync(COMPONENTS)
  .filter((f) => /\.(tsx|ts)$/.test(f))
  .map((f) => f.replace(/\.(tsx|ts)$/, ""))
  .sort();

// Every exported name across the folder, so a collision fails the build here
// rather than producing a barrel that silently drops one of them.
const owners = new Map();
for (const base of files) {
  const src = readFileSync(join(COMPONENTS, base + (readdirSync(COMPONENTS).includes(base + ".tsx") ? ".tsx" : ".ts")), "utf8");
  const names = [
    ...[...src.matchAll(/^export\s+(?:async\s+)?(?:function|const|class)\s+([A-Za-z0-9_]+)/gm)].map((m) => m[1]),
    ...[...src.matchAll(/^export\s*\{([^}]*)\}/gms)].flatMap((m) =>
      m[1].split(",").map((x) => x.trim().replace(/^type\s+/, "").split(/\s+as\s+/).pop()).filter(Boolean),
    ),
    ...[...src.matchAll(/^export\s+(?:type|interface)\s+([A-Za-z0-9_]+)/gm)].map((m) => m[1]),
  ];
  for (const n of new Set(names)) {
    if (!owners.has(n)) owners.set(n, []);
    owners.get(n).push(base);
  }
}
const clashes = [...owners].filter(([, v]) => v.length > 1);
if (clashes.length) {
  console.error("Export name collisions, the barrel would drop one of each:");
  for (const [n, v] of clashes) console.error(`  ${n} <- ${v.join(", ")}`);
  process.exit(1);
}

const header = `// Generated by scripts/build-barrel.mjs. Do not edit.
// ${files.length} modules, ${owners.size} exported names.
`;
writeFileSync(
  join(ROOT, "src", "index.ts"),
  header + files.map((b) => `export * from "./components/${b}";`).join("\n") + "\n",
);
console.log(`barrel: ${files.length} modules, ${owners.size} names`);
